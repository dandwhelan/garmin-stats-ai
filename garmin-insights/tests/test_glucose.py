def test_csv_point_dropped_when_nightscout_has_same_moment(tmp_path):
    db = str(tmp_path / "g.db")
    t0 = datetime(2026, 11, 20, 12, 0, tzinfo=timezone.utc)
    glucose.upsert_readings(db, _rows(t0, [5.0, 5.0], step_min=15))
    glucose.upsert_readings(db, _rows(t0, [6.0] * 31, step_min=1, source="nightscout", sensor=None))
    df = glucose.load_readings(db, t0 - timedelta(hours=1), t0 + timedelta(hours=1))
    assert set(df["source"]) == {"nightscout"}
    assert len(df) == 31


