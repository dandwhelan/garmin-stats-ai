def _flagged(db, start: datetime, values, step=15, sensor="S1"):
    glucose.upsert_readings(db, _rows(start, values, step, sensor=sensor))
    df = glucose.load_readings(db, start - timedelta(days=1), start + timedelta(days=30))
    return glucose.flag_quality(df)


def test_compression_low_flagged_overnight(tmp_path):
    db = str(tmp_path / "g.db")
    start = datetime(2026, 11, 20, 0, 0, tzinfo=timezone.utc)
    # Two days steady so day-1 early-sensor flags don't matter for the night of day 2.
    vals = [5.5] * (4 * 48)
    # 02:00 on day 2 (index 4*24 + 8): sudden dip to 3.0 for 45 min, then back.
    i = 4 * 24 + 8
    vals[i:i + 3] = [3.2, 3.0, 3.1]
    df = _flagged(db, start, vals)
    flagged = df[df["compression_low"]]
    assert len(flagged) == 3
    assert flagged["local"].dt.hour.min() == 2


def test_daytime_drop_not_flagged_as_compression(tmp_path):
    db = str(tmp_path / "g.db")
    start = datetime(2026, 11, 20, 0, 0, tzinfo=timezone.utc)
    vals = [5.5] * (4 * 48)
    i = 4 * 24 + 4 * 14  # 14:00 day 2
    vals[i:i + 3] = [3.2, 3.0, 3.1]
    df = _flagged(db, start, vals)
    assert not df["compression_low"].any()


def test_slow_overnight_fall_not_compression(tmp_path):
    db = str(tmp_path / "g.db")
    start = datetime(2026, 11, 20, 0, 0, tzinfo=timezone.utc)
    vals = [5.5] * (4 * 48)
    i = 4 * 24 + 4  # 01:00 day 2 — drift down over 2 h (0.0125 mmol/min)
    for k in range(8):
        vals[i + k] = 5.5 - 0.1875 * (k + 1)
    df = _flagged(db, start, vals)
    assert not df["compression_low"].any()


def test_early_sensor_first_24h_and_new_sensor(tmp_path):
    db = str(tmp_path / "g.db")
    start = datetime(2026, 11, 1, 0, 0, tzinfo=timezone.utc)
    glucose.upsert_readings(db, _rows(start, [5.5] * (4 * 48), sensor="A"))
    glucose.upsert_readings(db, _rows(start + timedelta(days=2), [5.5] * (4 * 30), sensor="B"))
    df = glucose.flag_quality(glucose.load_readings(db, start, start + timedelta(days=5)))
    assert df["session"].nunique() == 2
    a = df[df["sensor_id"] == "A"]
    b = df[df["sensor_id"] == "B"]
    assert a["early_sensor"].sum() == 4 * 24        # exactly the first 24 h
    assert b["early_sensor"].sum() == 4 * 24


