def test_api_glucose_import_and_get(api_client):
    today = datetime.now()
    lines = [
        "Glucose Data,Generated on,x,Generated by,y",
        "Device,Serial Number,Device Timestamp,Record Type,Historic Glucose mmol/L,Scan Glucose mmol/L",
    ]
    t = (today - timedelta(days=4)).replace(hour=0, minute=0, second=0, microsecond=0)
    for i in range(96 * 3):
        ts = t + timedelta(minutes=15 * i)
        lines.append(f"FreeStyle LibreLink,S9,{ts:%d-%m-%Y %H:%M},0,6.1,")
    r = api_client.post("/api/glucose/import", json={"user": "default", "csv": "\n".join(lines)})
    assert r.status_code == 200, r.text
    body = r.json()
    assert body["imported"] == 96 * 3
    assert body["days_rebuilt"] >= 3

    g = api_client.get(f"/api/glucose?user=default&start={t:%Y-%m-%d}&end={today:%Y-%m-%d}").json()
    assert g["available"] is True
    assert g["window"]["mean_mmol"] == 6.1
    assert g["series"]

    day = (t + timedelta(days=1)).strftime("%Y-%m-%d")
    dash = api_client.get(f"/api/dashboard?user=default&start={day}&end={day}").json()
    summaries = dash.get("summaries") or dash.get("daily") or []
    match = [s for s in summaries if s.get("date") == day]
    assert match and match[0].get("glucose_mean_mmol") == 6.1


