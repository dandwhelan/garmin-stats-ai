def test_parse_nightscout_entries_skips_non_sgv_and_sentinels():
    ms = int(datetime(2026, 11, 20, 7, 0, tzinfo=timezone.utc).timestamp() * 1000)
    rows = glucose_fetch.parse_entries([
        {"type": "sgv", "sgv": 104, "date": ms, "direction": "Flat", "device": "Juggluco"},
        {"type": "mbg", "mbg": 110, "date": ms},
        {"type": "sgv", "sgv": 39, "date": ms + 60000},          # sensor error code
        {"sgv": 120, "dateString": "2026-11-20T07:02:00.000Z"},
        "junk",
    ])
    assert [r["mg_dl"] for r in rows] == [104, 120]
    assert rows[0]["time"] == "2026-11-20T07:00:00Z"
    assert rows[1]["time"] == "2026-11-20T07:02:00Z"


def test_entries_url_variants():
    assert glucose_fetch.entries_url("http://phone:17580") == "http://phone:17580/api/v1/entries.json"
    assert glucose_fetch.entries_url("https://ns.x/api/v1/") == "https://ns.x/api/v1/entries.json"
    assert glucose_fetch.entries_url("http://phone:17580/sgv.json") == "http://phone:17580/sgv.json"


def test_fetch_from_env_noop_without_url(monkeypatch, tmp_path):
    monkeypatch.delenv("NIGHTSCOUT_URL", raising=False)
    assert glucose_fetch.fetch_from_env() == 0


def test_fetcher_upsert_then_backfill_window(monkeypatch, tmp_path):
    db = str(tmp_path / "g.db")
    glucose_fetch.upsert(db, [{"time": "2026-11-20T07:00:00Z", "mg_dl": 100.0}])
    seen = {}

    def fake_fetch(url, since, token="", api_secret=""):
        seen["since"] = since
        return [{"time": "2026-11-20T07:01:00Z", "mg_dl": 101.0}]

    monkeypatch.setattr(glucose_fetch, "fetch_entries", fake_fetch)
    monkeypatch.setenv("NIGHTSCOUT_URL", "http://phone:17580")
    monkeypatch.setenv("SQLITE_DB_PATH", db)
    assert glucose_fetch.fetch_from_env() == 1
    # Resumes from the newest stored reading minus the overlap.
    assert seen["since"] == datetime(2026, 11, 20, 6, 30, tzinfo=timezone.utc)


