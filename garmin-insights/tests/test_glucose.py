def _seed_recent(db: str, days_ago_start: int = 5, days: int = 4):
    start = (datetime.now(timezone.utc) - timedelta(days=days_ago_start)).replace(
        hour=0, minute=0, second=0, microsecond=0)
    glucose.upsert_readings(db, _rows(start, [5.6] * (96 * days), sensor="A"))
    return start


def test_cache_merges_glucose_into_daily_summaries(sample_settings):
    from garmin_insights.db.cache import CacheBuilder
    from garmin_insights.db.memory import MemoryStore
    from garmin_insights.db.sqlite_repo import SqliteRepo

    start = _seed_recent(sample_settings.sqlite_db_path)
    day = (start + timedelta(days=2)).strftime("%Y-%m-%d")
    memory = MemoryStore(sample_settings)
    cache = CacheBuilder(SqliteRepo(sample_settings), memory)
    summary = cache.build_daily_summary(day)
    assert summary["glucose_mean_mmol"] == 5.6
    assert summary["glucose_tir_pct"] == 100.0
    assert "restingHeartRate" in summary                # still merged with Garmin data


def test_agent_tool_get_glucose_data(sample_settings):
    from garmin_insights.db.memory import MemoryStore
    from garmin_insights.db.sqlite_repo import SqliteRepo
    from garmin_insights.tools.query_tools import QueryToolHandler, get_all_tools_anthropic

    start = _seed_recent(sample_settings.sqlite_db_path)
    handler = QueryToolHandler(SqliteRepo(sample_settings), MemoryStore(sample_settings), None)
    names = [t["name"] for t in get_all_tools_anthropic(handler)]
    assert "get_glucose_data" in names
    day = (start + timedelta(days=2)).strftime("%Y-%m-%d")
    out = json.loads(handler.get_glucose_data(intraday_date=day))
    assert out["available"] is True
    assert out["days"][day]["glucose_mean_mmol"] == 5.6
    assert out["intraday"]["mmol_by_time"]["08:00"] == 5.6
    assert "series" not in out


