def test_daily_metrics_values_and_coverage_gate(tmp_path):
    db = str(tmp_path / "g.db")
    start = datetime(2026, 11, 1, 0, 0, tzinfo=timezone.utc)
    day1 = [5.0] * 96
    day2 = [5.0] * 48 + [9.0] * 48        # half the day above 7.8
    day3 = [5.0] * 20                      # ~21% coverage — gated out
    glucose.upsert_readings(db, _rows(start, day1 + day2 + day3, sensor="A"))
    m = glucose.daily_metrics(db, "2026-11-01", "2026-11-03")
    assert "glucose_mean_mmol" not in m["2026-11-01"]       # early sensor day excluded
    d2 = m["2026-11-02"]
    assert d2["glucose_mean_mmol"] == 7.0
    assert d2["glucose_tir_pct"] == 50.0
    assert d2["glucose_above_pct"] == 50.0
    assert d2["glucose_fasting_mmol"] == 5.0
    assert d2["glucose_coverage_pct"] == 100
    assert "glucose_mean_mmol" not in m["2026-11-03"]
    assert m["2026-11-03"]["glucose_coverage_pct"] < glucose.MIN_DAY_COVERAGE_PCT


