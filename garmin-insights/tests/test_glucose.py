def _rows(start: datetime, values_mmol, step_min: int = 15, source="libreview_csv", sensor="S1"):
    return [
        {
            "time": (start + timedelta(minutes=i * step_min)).strftime("%Y-%m-%dT%H:%M:%SZ"),
            "source": source, "mg_dl": round(v * glucose.MGDL_PER_MMOL, 1),
            "sensor_id": sensor, "record_type": "historic",
        }
        for i, v in enumerate(values_mmol)
    ]


