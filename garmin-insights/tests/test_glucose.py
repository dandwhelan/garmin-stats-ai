def test_parse_uk_csv_mmol_day_first():
    rows = glucose.parse_libreview_csv(_UK_CSV)
    assert [r["record_type"] for r in rows] == ["historic", "historic", "scan"]
    assert rows[0]["time"] == "2026-11-13T08:00:00Z"
    assert rows[0]["mg_dl"] == pytest.approx(5.2 * glucose.MGDL_PER_MMOL, abs=0.1)
    assert rows[0]["sensor_id"] == "ABC123"


def test_parse_us_csv_mgdl_month_first():
    rows = glucose.parse_libreview_csv(_US_CSV)
    assert rows[0]["time"] == "2026-11-13T13:00:00Z"
    assert rows[1]["mg_dl"] == 126


